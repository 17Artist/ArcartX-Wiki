export function NietzscheQuote() {
  const [quote, setQuote] = useState('');

  useEffect(() => {
    setQuote(quotes[Math.floor(Math.random() * quotes.length)]);
  }, []);

  if (!quote) return null;

  return (
    <div className="nietzsche-quote">
      <span className="nietzsche-quote-text">{quote}</span>
      <span className="nietzsche-quote-author">—— 弗里德里希·尼采</span>
    </div>
  );
}
